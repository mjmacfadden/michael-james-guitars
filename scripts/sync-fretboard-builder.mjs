#!/usr/bin/env node
// Copy the Fretboard Builder ENGINE from the standalone repo (mjmacfadden/fretboard-builder)
// into fretboard-builder/engine/ and record exactly which upstream commit it came from.
//
// Usage (from the repo root):
//   node scripts/sync-fretboard-builder.mjs                    # uses ../fretboard-builder (sibling checkout)
//   node scripts/sync-fretboard-builder.mjs /path/to/fretboard-builder
//   node scripts/sync-fretboard-builder.mjs --check            # only verify engine files match UPSTREAM.json
//
// The upstream checkout must be clean (everything committed) so the recorded commit is the truth.
// After syncing: run `node fretboard-builder/engine/test.js` and `npm --prefix functions test`, then commit.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const engineDir = path.join(root, 'fretboard-builder', 'engine');
const manifestPath = path.join(root, 'fretboard-builder', 'UPSTREAM.json');
// Files taken verbatim from upstream. Everything else in fretboard-builder/ is store-specific.
// index.html is the standalone page: kept for test.js (it reads the form markup) and as the
// reference the store page's controls are checked against. It is not published by Hosting.
export const ENGINE_FILES = ['geometry.js', 'stl.js', 'app.js', 'test.js', 'index.html', 'LICENSE', 'vendor/earcut.min.js', 'vendor/earcut-LICENSE'];

const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');

function check() {
  const m = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const bad = ENGINE_FILES.filter((f) => !existsSync(path.join(engineDir, f)) || sha256(path.join(engineDir, f)) !== m.files[f]);
  if (bad.length) {
    console.error(`Engine files differ from upstream ${m.repo}@${m.commit.slice(0, 7)}: ${bad.join(', ')}`);
    console.error('Make engine changes in the fretboard-builder repo, then re-run this sync script.');
    process.exit(1);
  }
  console.log(`fretboard engine matches ${m.repo}@${m.commit.slice(0, 7)}`);
}

function sync(src) {
  if (!existsSync(path.join(src, 'geometry.js'))) throw new Error(`No fretboard-builder checkout at ${src}`);
  const git = (...a) => execFileSync('git', ['-C', src, ...a], { encoding: 'utf8' }).trim();
  const dirty = git('status', '--porcelain', '--', ...ENGINE_FILES);
  if (dirty && !process.argv.includes('--allow-dirty')) throw new Error(`Upstream has uncommitted engine changes; commit them first:\n${dirty}`);
  const commit = git('rev-parse', 'HEAD');
  const files = {};
  for (const f of ENGINE_FILES) {
    mkdirSync(path.dirname(path.join(engineDir, f)), { recursive: true });
    copyFileSync(path.join(src, f), path.join(engineDir, f));
    files[f] = sha256(path.join(engineDir, f));
  }
  const manifest = {
    _comment: 'GENERATED by scripts/sync-fretboard-builder.mjs. Engine files are copied verbatim from upstream; do not edit them here.',
    repo: 'mjmacfadden/fretboard-builder',
    commit,
    engineVersion: `fretboard-builder@${commit.slice(0, 7)}`,
    files,
  };
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  // Stamp the engine version on the page so saved/shared designs record which geometry made them.
  const page = path.join(root, 'fretboard-builder.html');
  writeFileSync(page, readFileSync(page, 'utf8').replace(/data-engine-version="[^"]*"/, `data-engine-version="${manifest.engineVersion}"`));
  console.log(`Synced engine from ${src} at ${commit.slice(0, 7)}. Now run: node fretboard-builder/engine/test.js && npm --prefix functions test`);
}

const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
if (process.argv.includes('--check')) check();
else sync(path.resolve(args[0] || path.join(root, '..', 'fretboard-builder')));
